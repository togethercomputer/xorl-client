"""No-filler OPSD multiplication task: distill a CoT-conditioned teacher's
PEAKED answer distribution onto a DIRECT-answer student (single-shot).

This is the ES (ZORL) port of the gradient "no-filler OPSD" 4x4-multiplication
recipe (xorl-apanda-dev-opd-port/experiments/opd_profile/
HOWTO_NOFILLER_OPSD_TRAINING.md). On 4-digit x 4-digit multiplication the
gradient arm lifts DIRECT accuracy 0.594 -> ~0.88; here we test whether ES can
do the same optimization.

The objective (single-shot, NOT multi-turn):
  * STUDENT input:  ``<user prompt> + "Answer: "`` -- no CoT, no filler. It
    samples the answer directly.
  * TEACHER input:  ``<user prompt> + "\n" + <CoT> + "\n" + "Answer: "`` -- the
    same model weights (self-distill); the CoT is its private scratch.
  * KL is over the student's ANSWER token positions only (the shared sampled
    continuation ``oid``), computed full-vocab server-side in SGLang.

KL coherence: both prefixes share the SAME chat-template user turn and BOTH end
with the literal ``Answer: `` cue, so the student's sampled ``oid`` (the answer
digits) lands at the identical logical position in both contexts. The teacher
prefix differs ONLY by the inserted CoT, which is exactly the OPSD asymmetry --
distilling the CoT-conditioned answer distribution into the direct student.

Prompt format (matches the production OPD data + the runbook's
``student_prefill_suffix: 'Answer: '``):
  * The dataset prompts are chat messages ``[{"role":"user","content":
    "/no_think Calculate: A * B"}]``. The CoT json was generated by applying the
    chat template to that user turn (``add_generation_prompt=True``) and letting
    the model produce the assistant reply ``<think>...reasoning...</think>\n\n
    Answer: <product>``. So we use the CHAT TEMPLATE for the user turn (the
    production format) and append the prefill/CoT as raw assistant-turn text --
    identical to ``opd_multiplication._build_prompt_ids`` and the OPD trainer's
    chat-template-user + raw-assistant-prefill convention.
  * The stored CoT text starts with the reasoning directly (the ``<think>``
    opener is consumed by the chat template) and ends with an optional
    ``</think>`` then ``Answer: <product>``. We STRIP the CoT's own trailing
    ``Answer: <product>`` and ``</think>`` so the CoT becomes pure scratch and
    the ``Answer: `` boundary is not duplicated (the teacher's scratch still
    derives the product, which peaks its answer distribution -- that is the
    distillation target).

Data (``/shared/opd-coord/``):
  * Prompts: ``randnum_4digit_8192.json`` (8192 chat-message lists).
  * CoT:     ``randnum_4digit_8192_cot_mt8192.json`` (the long-mt CoT; the
    HOWTO says use the mt8192 file, NOT the amputated ``_cot.json``). A list of
    ``{prompt, cot, finish_reason, tokens}``. The two files are index-aligned
    on ``prompt`` (verified 8192/8192); we still align by the ``prompt`` field
    defensively and filter to non-empty (post-strip) CoT pairs.

Reward (training): full-vocab OPSD KL, computed server-side (this module only
supplies ``build_opsd_prompts``). Probe/eval: greedy DIRECT accuracy via the
client's single-shot OPSD probe (``opsd_kl and not opsd_multi_turn``), which is
Wordle-shaped (calls ``extract_guesses``/``compute_feedback`` and reads
``metadata['target']``); we provide thin shims so the probe reports DIRECT
exact-match accuracy of the parsed integer answer against the product.
"""

