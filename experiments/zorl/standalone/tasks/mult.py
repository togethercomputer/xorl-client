if __name__ == "__main__":
    print("Running mult sanity checks...")

    # Operand / product parsing.
    assert _parse_operands("/no_think Calculate: 2824 * 1409") == (2824, 1409)
    assert _parse_operands("Calculate: 9999 * 1") == (9999, 1)

    # CoT stripping: removes the CoT's own Answer line + </think>, keeps scratch.
    sample = "step 1\nstep 2\n3979016\n</think>\n\nAnswer: 3979016"
    stripped = _strip_cot(sample)
    assert "Answer:" not in stripped, stripped
    assert "</think>" not in stripped, stripped
    assert "step 1" in stripped and "step 2" in stripped, stripped

    # Direct-answer scoring.
    ex = Example(
        project="t",
        prompt_ids=[],
        metadata={
            "prompt_text": "/no_think Calculate: 2824 * 1409",
            "cot_text": "scratch",
            "product": 2824 * 1409,
            "target": str(2824 * 1409),
        },
    )
    assert score_completion(ex, "3979016")["exact_match"] == 1.0
    assert score_completion(ex, "3,979,016")["exact_match"] == 1.0  # comma sep
    assert score_completion(ex, "The answer is 3979016")["exact_match"] == 1.0
    assert score_completion(ex, "1234567")["exact_match"] == 0.0
    r = score_completion(ex, "")
    assert r["exact_match"] == 0.0 and r["format_rate"] == 0.0, r  # EOS collapse
    # First integer is the direct answer (student samples right after "Answer: ").
    assert score_completion(ex, "3979016 done")["exact_match"] == 1.0

    # Probe shims.
    assert extract_guesses("3979016") == ["3979016"]
    assert extract_guesses("") == []
    assert compute_feedback("3979016", "3979016") == "GGGGG"
    assert compute_feedback("123", "3979016") == "XXXXX"

    # Build a few real examples + decode student vs teacher prefixes.
