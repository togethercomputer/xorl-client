# ---------------------------------------------------------------------------
# Data paths (the long-mt CoT, per HOWTO_NOFILLER_OPSD_TRAINING.md §5)
# ---------------------------------------------------------------------------

PROMPTS_JSON = os.environ.get("ZORL_MULT_PROMPTS_JSON", "/shared/opd-coord/randnum_4digit_8192.json")
COT_JSON = os.environ.get("ZORL_MULT_COT_JSON", "/shared/opd-coord/randnum_4digit_8192_cot_mt8192.json")

# Match the HOWTO's ``student_prefill_suffix: 'Answer: '``. This is the shared
# boundary at which the student samples its answer; the teacher sees the CoT
# inserted before this identical cue.
STUDENT_PREFILL_SUFFIX = "Answer: "

_PRODUCT_RE = re.compile(r"(\d+)\s*\*\s*(\d+)")
_INTEGER_TOKEN_RE = re.compile(r"-?\d[\d,]*")


# ---------------------------------------------------------------------------
# Operand / product parsing
# ---------------------------------------------------------------------------


def _user_text(prompt_field) -> str:
    """Extract the user message text from a stored prompt field.

    Prompts are chat-message lists ``[{"role":"user","content":"..."}]``; accept
    a raw string too for robustness."""
    if isinstance(prompt_field, str):
        return prompt_field
    if isinstance(prompt_field, list) and prompt_field:
        first = prompt_field[0]
        if isinstance(first, dict):
            return str(first.get("content", ""))
    raise ValueError(f"Unrecognized prompt field shape: {prompt_field!r}")


def _parse_operands(user_text: str) -> tuple[int, int]:
    """Parse the two integer operands from ``Calculate: A * B``. Raises if the
    prompt doesn't match the expected shape."""
    m = _PRODUCT_RE.search(user_text)
    if m is None:
        raise ValueError(f"Could not parse 'A * B' from prompt: {user_text!r}")
    return int(m.group(1)), int(m.group(2))


def _strip_cot(cot: str) -> str:
    """Reduce a stored CoT to pure private scratch: drop its own trailing
    ``Answer: <product>`` line and a trailing ``</think>`` close, so the teacher
    prefix ends at the shared ``Answer: `` cue (no duplicate cue / no doubled
    answer-position)."""
    s = cot or ""
    idx = s.rfind("Answer:")
    if idx != -1:
        s = s[:idx]
    s = re.sub(r"</think>\s*$", "", s.rstrip())
    return s.strip()


# ---------------------------------------------------------------------------
# Data loading (cached at module load; aligned + filtered once)
# ---------------------------------------------------------------------------


def _load_aligned_pairs(prompts_path: str, cot_path: str) -> list[dict]:
    """Load prompts + CoTs, align by the ``prompt`` field, strip each CoT to
    pure scratch, and keep only pairs with a parseable product and a non-empty
    stripped CoT. Returns a list of ``{user_text, a, b, product, cot}``."""
    p_path, c_path = Path(prompts_path), Path(cot_path)
    if not p_path.exists():
        raise FileNotFoundError(f"mult prompts not found at {p_path}")
    if not c_path.exists():
        raise FileNotFoundError(f"mult CoT not found at {c_path}")
    with p_path.open() as f:
        prompts = json.load(f)
    with c_path.open() as f:
        cots = json.load(f)

    # Index CoTs by their user-text key so we align by content, not position.
    cot_by_key: dict[str, str] = {}
    for row in cots:
        try:
            key = _user_text(row.get("prompt"))
        except ValueError:
            continue
        cot_by_key.setdefault(key, row.get("cot") or "")

    pairs: list[dict] = []
    for entry in prompts:
        try:
            user_text = _user_text(entry)
            a, b = _parse_operands(user_text)
        except ValueError:
            continue
        raw_cot = cot_by_key.get(user_text)
        if raw_cot is None:
            continue
        cot = _strip_cot(raw_cot)
        if not cot:
            continue
        pairs.append({"user_text": user_text, "a": a, "b": b, "product": a * b, "cot": cot})
    if not pairs:
        raise RuntimeError(
            f"No usable (prompt, CoT) pairs from {prompts_path} + {cot_path}. "
            "Check alignment / non-empty CoT filtering."
        )
    return pairs


# Loaded once at import (the CoT file is ~50 MB; never reload per call). Skipped
# in synthetic mode, which generates operands directly and needs no file/CoTs.
if os.environ.get("ZORL_MULT_SYNTHETIC", "0") == "1":
    _PAIRS: list[dict] = []
    NUM_USABLE_PAIRS = 0
else:
    _PAIRS = _load_aligned_pairs(PROMPTS_JSON, COT_JSON)
    NUM_USABLE_PAIRS = len(_PAIRS)


# ---------------------------------------------------------------------------
# Prompt construction
# ---------------------------------------------------------------------------


def _chat_user_prefix_ids(tokenizer, user_text: str) -> list[int]:
    """Chat-template the user turn with ``add_generation_prompt=True`` -- the
    canonical ``<|im_start|>user...<|im_end|>\n<|im_start|>assistant\n`` prefix
    the CoTs were generated from."""
    msgs = [{"role": "user", "content": user_text}]
    return list(
        tokenizer.apply_chat_template(
            msgs,
            tokenize=True,
            add_generation_prompt=True,
            enable_thinking=False,  # /no_think is already in the user content
            return_dict=False,
        )
    )


# ---------------------------------------------------------------------------
# Examples
# ---------------------------------------------------------------------------


# Synthetic mode: 4-digit operands are free to generate, so the train pool can
# be effectively infinite (no dependence on the 8192-row precomputed file, which
# only carried CoTs the SFT objective never reads). Gate with ZORL_MULT_SYNTHETIC=1
# and set a large --train-pool-size; eval stays a FIXED disjoint held-out set.
SYNTHETIC = os.environ.get("ZORL_MULT_SYNTHETIC", "0") == "1"


def _synthetic_pair(rng: random.Random) -> dict:
    a = rng.randint(1000, 9999)
    b = rng.randint(1000, 9999)
    return {
        "user_text": f"/no_think Calculate: {a} * {b}",
        "a": a,
        "b": b,
        "product": a * b,
        "cot": "",  # unused by sft/teacher_forced; opsd_kl modes need the file path
    }


def _build_synthetic_examples(tokenizer, *, train_size: int, eval_size: int, seed: int):
    """Generate train/eval from freshly synthesized 4-digit problems. Eval is a
    fixed seeded set; train is drawn disjoint from it (collisions are astronomically
    rare at 8.1e7 possible operand pairs but rejected anyway for cleanliness)."""
    eval_rng = random.Random(seed * 1_000_003 + 7)
    eval_pairs, eval_keys = [], set()
    while len(eval_pairs) < eval_size:
        p = _synthetic_pair(eval_rng)
        k = (p["a"], p["b"])
        if k in eval_keys:
            continue
        eval_keys.add(k)
        eval_pairs.append(p)

    train_rng = random.Random(seed * 1_000_003 + 11)
    train_pairs = []
    while len(train_pairs) < train_size:
        p = _synthetic_pair(train_rng)
        if (p["a"], p["b"]) in eval_keys:
            continue
        train_pairs.append(p)

    def to_example(pair: dict, pid: str) -> Example:
        student_ids = _chat_user_prefix_ids(tokenizer, pair["user_text"])
        student_ids = student_ids + list(tokenizer.encode(STUDENT_PREFILL_SUFFIX, add_special_tokens=False))
        return Example(
            project=pid,
            prompt_ids=student_ids,
            metadata={
                "prompt_text": pair["user_text"], "cot_text": pair["cot"],
                "product": int(pair["product"]), "a": int(pair["a"]), "b": int(pair["b"]),
                "target": str(int(pair["product"])),
            },
        )

    train = [to_example(p, f"mult_train_{i:06d}") for i, p in enumerate(train_pairs)]
    eval_ = [to_example(p, f"mult_eval_{i:05d}") for i, p in enumerate(eval_pairs)]
    return train, eval_


def build_examples(tokenizer, *, train_size: int = 8, eval_size: int = 128, seed: int = 0):
    """Pick disjoint train/eval problems from the aligned pairs (seeded
    shuffle). ``prompt_ids`` holds the STUDENT direct-answer prompt
    (chat-template user + ``Answer: ``) so any single-shot fallback can use it;
    the OPSD path rebuilds both prefixes via ``build_opsd_prompts``."""
    if SYNTHETIC:
        return _build_synthetic_examples(tokenizer, train_size=train_size, eval_size=eval_size, seed=seed)
    if NUM_USABLE_PAIRS < train_size + eval_size:
        raise ValueError(f"only {NUM_USABLE_PAIRS} usable pairs, need >= {train_size + eval_size} for train+eval")
    rng = random.Random(seed)
    order = list(range(NUM_USABLE_PAIRS))
    rng.shuffle(order)
    train_idx = order[:train_size]
    eval_idx = order[train_size : train_size + eval_size]

    def to_example(pair_idx: int, pid: str) -> Example:
        pair = _PAIRS[pair_idx]
        student_ids = _chat_user_prefix_ids(tokenizer, pair["user_text"])
        student_ids = student_ids + list(tokenizer.encode(STUDENT_PREFILL_SUFFIX, add_special_tokens=False))
        return Example(
            project=pid,
            prompt_ids=student_ids,
            metadata={
                "prompt_text": pair["user_text"],
                "cot_text": pair["cot"],
                "product": int(pair["product"]),
                "a": int(pair["a"]),
                "b": int(pair["b"]),
                # The single-shot OPSD probe (Wordle-shaped) reads metadata["target"];
                # the product string is the direct-answer target it checks against.
                "target": str(int(pair["product"])),
            },
        )

    train = [to_example(j, f"mult_train_{i:05d}") for i, j in enumerate(train_idx)]
    eval_ = [to_example(j, f"mult_eval_{i:05d}") for i, j in enumerate(eval_idx)]
    return train, eval_


# ---------------------------------------------------------------------------
# OPSD prefixes (the contract zorl_client's opsd_kl_full branch consumes)
# ---------------------------------------------------------------------------


def build_opsd_prompts(tokenizer, example: Example, *, args) -> tuple[list[int], list[int]]:
    """Return ``(student_prefix_ids, teacher_prefix_ids)`` for single-shot OPSD.

    student_prefix = chat_template(user) + "Answer: "
    teacher_prefix = chat_template(user) + "\n" + <CoT scratch> + "\n" + "Answer: "

    Both share the chat-template user turn and BOTH end with the literal
    ``Answer: `` cue; the teacher differs only by the inserted CoT. The client
    samples the student continuation ``oid`` from student_prefix, then scores the
    full-vocab KL over ``oid`` at the student vs the teacher prefix (both
    prefixed before the SAME ``oid``)."""
    user_text = str(example.metadata["prompt_text"])
    cot_text = str(example.metadata["cot_text"])
    base_ids = _chat_user_prefix_ids(tokenizer, user_text)

    suffix_ids = tokenizer.encode(STUDENT_PREFILL_SUFFIX, add_special_tokens=False)
    student_prefix = list(base_ids) + list(suffix_ids)

    teacher_tail = "\n" + cot_text + "\n" + STUDENT_PREFILL_SUFFIX
    teacher_prefix = list(base_ids) + list(tokenizer.encode(teacher_tail, add_special_tokens=False))
    return student_prefix, teacher_prefix


# ---------------------------------------------------------------------------
# SFT target (the contract zorl_client's teacher_forced / sft branch consumes)
# ---------------------------------------------------------------------------


def build_teacher_forced_example(tokenizer, example: Example, *, args=None) -> Example:
    """Teacher-forced / SFT target: the correct product digits placed right after
    the shared ``Answer: `` cue.

    Returns an Example whose ``prompt_ids`` is the FULL teacher-forced sequence
    (student direct-answer prompt ``chat_template(user) + "Answer: "`` followed by
    the ground-truth product string) and whose
    ``metadata['teacher_target_token_count']`` is the number of answer tokens to
    score. The client requests teacher-forced input logprobs over this sequence
    and scores the mean logprob of the last ``teacher_target_token_count`` tokens
    (the product) under each candidate LoRA -- i.e. the negative SFT loss on the
    direct answer. With ``--score-mode sft`` the candidate reward IS that mean
    logprob, so maximizing it via ES is exactly supervised fine-tuning toward the
    correct answer. The cue is byte-identical to ``build_opsd_prompts``' student
    prefix and ``build_examples``' ``prompt_ids`` so the scored answer position
    matches where the student actually samples at probe time."""
    user_text = str(example.metadata["prompt_text"])
    product_str = str(int(example.metadata["product"]))
    base_ids = _chat_user_prefix_ids(tokenizer, user_text)
    suffix_ids = list(tokenizer.encode(STUDENT_PREFILL_SUFFIX, add_special_tokens=False))
    student_prompt_ids = list(base_ids) + suffix_ids
    target_ids = list(tokenizer.encode(product_str, add_special_tokens=False))
    if not target_ids:
        raise ValueError(f"empty SFT target tokens for product {product_str!r}")
    full_ids = student_prompt_ids + target_ids
    return Example(
        project=example.project,
        prompt_ids=full_ids,
        metadata={**example.metadata, "teacher_target_token_count": len(target_ids)},
    )


# ---------------------------------------------------------------------------
# Scoring + probe shims
# ---------------------------------------------------------------------------


def _parse_answer(generated_text: str) -> int | None:
    """Extract the first integer from a direct answer. The student samples right
    after ``Answer: ``, so the first integer-shaped run is its answer; strip
    comma thousands separators first."""
    if not generated_text:
        return None
    cleaned = generated_text.replace(",", "")
    nums = _INTEGER_TOKEN_RE.findall(cleaned)
    if not nums:
        return None
    try:
        return int(nums[0])
    except ValueError:
        return None


def score_completion(example: Example, generated_text: str) -> dict[str, float]:
    """DIRECT-answer scorer: 1.0 iff the first parsed integer equals A*B.

    ``format_rate`` = did the student emit any integer at all (catches the
    EOS-collapse failure mode where the student emits nothing after the cue)."""
    parsed = _parse_answer(generated_text)
    correct = float(parsed is not None and parsed == int(example.metadata["product"]))
    return {
        "reward": correct,
        "exact_match": correct,
        "format_rate": float(parsed is not None),
        "info_gain": 0.0,
        "turns_used": 1,
    }


# --- Single-shot OPSD probe shims (Wordle-shaped probe path in zorl_client) ---
# The client's ``opsd_kl and not opsd_multi_turn`` probe is Wordle-shaped: it
# calls task.extract_guesses(text) + task.compute_feedback(guess, target) and
# checks ``target in guesses`` for exact_match. We expose those names so the
# probe reports DIRECT greedy accuracy: a "guess" is the parsed integer answer
# (as a string), and "feedback" is all-green iff it equals the product.


def extract_guesses(text: str) -> list[str]:
    """The student's direct answer as a single-element ``[answer_str]`` list
    (empty if it emitted no integer). The probe checks ``target in guesses`` for
    exact-match accuracy."""
    parsed = _parse_answer(text or "")
    return [] if parsed is None else [str(parsed)]


def compute_feedback(guess: str, target: str) -> str:
    """Wordle-style dense feedback shim for the probe's ``closeness`` signal:
    all-``G`` iff the parsed answer equals the target product, else all-``X``."""
    return ("G" * 5) if str(guess) == str(target) else ("X" * 5)


